"""Full gz-sim (Harmonic / ROS 2 Jazzy) bring-up of the LMIC-HospitalNav stack:
photoreal hospital world + the REAL MentorPi Ackermann robot + SLAM + Nav2 +
the trained route planner + the trained RL policy + the swept-path shield.

    ros2 launch hospitalnav_deploy gz_bringup.launch.py preset:=residual_sf
    ros2 launch hospitalnav_deploy gz_bringup.launch.py preset:=vanilla tier:=open
    ros2 launch hospitalnav_deploy gz_bringup.launch.py preset:=residual_sf \\
         escape_enabled:=false gui:=true rviz:=true

WHY THIS FILE EXISTS (and gazebo_full_bringup.launch.py does not run here)
  The shipped launch targets Gazebo Classic via gazebo_ros + spawn_entity.py.
  Classic is gone with Humble and does not exist on Ubuntu 24.04 / Jazzy, so the
  simulator is gz-sim Harmonic through ros_gz, and the box robot is replaced by
  the real MentorPi description (urdf/mentorpi_real.urdf, vendor meshes and CAD
  link origins, Ackermann steering, LD19-spec lidar).

PRESETS
  A policy .zip is only valid with its OWN vec_normalize.pkl - a mismatched
  normaliser silently destroys performance rather than failing - and each agent
  also needs its own cultural_ratio and algo. 'preset' sets all of them together
  from MANIFEST.json's recommended seed, so the pairing cannot be got wrong by
  hand. Override any individual argument afterwards if you need to.

FRAMES
  odom->base_link comes from gz's OdometryPublisher system in the URDF, which
  reports the chassis's TRUE world pose (measured: 37, 15 at the spawn point),
  so the odom frame is the world frame and every coordinate (goals, zones, the
  semantic map) is already in the frame the policies were trained in. The
  AckermannSteering plugin's own wheel odometry is dead reckoning and drifted
  by 15-25 m in a 70 s test drive, so it is published only as a diagnostic
  (/odom_wheel) and nothing navigates on it. map->odom comes from whichever
  map source is selected: a static identity (map_source:=prebuilt, the
  default) or slam_toolbox (map_source:=slam).

PEDESTRIANS (peds:=none|light|busy|crowd45, people_source:=lidar|gt)
  peds splices ped_routes' scripted walking actors into a per-launch copy of
  the world (the shipped worlds stay the static benchmark scenes). The LD19
  sees the actors, so with people_source:=lidar (default) the deployment
  stack's own LiDAR people tracker feeds the policy, exactly as on the robot;
  people_source:=gt feeds it the actors' true states instead (ped_gt ->
  gt_pedestrians). Either way ped_gt publishes the ground truth for the
  proximity metrics in the run CSV and the sequencer's record.

TIERS
  walled / open are the benchmark tiers (scan-identical to the trained
  geometry). real overlays photogrammetry assets, still scan-identical.
  furnished adds floor-standing furniture WITH collision that the prebuilt
  map does not contain - the unmapped-clutter stress test - and uses the
  walled map on purpose.

MAP SOURCE, AND WHY PREBUILT IS THE DEFAULT
  The real workflow in MENTORPI_DEPLOYMENT.md maps the ward first (manual SLAM
  drive -> save map -> localise -> autonomous runs), and the route planner was
  trained planning over the full known layout. map_source:=prebuilt reproduces
  both, loading worlds/hospital_map_<tier>.yaml (generated by sim/gen_map.py
  from the same hospital.world the benchmark used).

  map_source:=slam maps live instead. It deadlocks from a standing start, for
  reasons that have nothing to do with any policy - see the comment at the map
  source block - so it is for demonstrating live mapping, not for running the
  campaign.

  With the prebuilt map, map->odom is a static identity: localisation is ground
  truth. That is deliberate - a run then measures the navigation policy rather
  than localisation drift - and it is stated in the results rather than implied.
"""
import os
import tempfile

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import (DeclareLaunchArgument, GroupAction, IncludeLaunchDescription,
                            OpaqueFunction, SetEnvironmentVariable, TimerAction)
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node, SetRemap

# models/ sits beside the package source in the ros_sim distribution
MODELS_DIR = os.environ.get(
    "HOSPITALNAV_MODELS",
    os.path.join(os.path.expanduser("~"), "Documents", "ros_sim", "models"))

