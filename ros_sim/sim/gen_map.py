"""Rasterises the trained world's collision geometry into a ready-made
occupancy map (PGM + YAML) for nav2_map_server.

WHY A PRE-BUILT MAP
  MENTORPI_DEPLOYMENT.md's real-robot workflow is: manual SLAM drive -> zone
  label PNG -> localization -> autonomous runs. The ward is mapped FIRST, and
  the autonomous runs then localise against that saved map. The Gazebo runs
  mirror that, and doing so removes a confound that has nothing to do with the
  policies: with live SLAM from a standing start, the only mapped area is what
  the first scan saw, the route planner has no route to any destination beyond
  it, so the robot never moves - and because it never moves, the map never
  grows. Pre-building the map is both closer to the documented deployment and
  the condition the route planner was trained under (it planned on the full
  known layout, not on a partial one).

WHAT IS RASTERISED
  Exactly the collision geometry of worlds/hospital.world - the world the
  runs_v5 benchmark numbers refer to - taken through the same parser
  gen_worlds.py uses, so the map cannot drift from the world. The lidar sees
  only a horizontal slice at z = 0.1535 m, so a prop is drawn into the map only
  if it spans that height; everything else (floor tints, signage, luminaires)
  is correctly absent.

    python3 gen_map.py                 # walled tier -> worlds/hospital_map.*
    python3 gen_map.py --tier open     # Tier-1: outer shell only
"""
from __future__ import annotations
import argparse
import os

import numpy as np

import gen_worlds as G

RES = 0.05            # m per cell, matching the SLAM maps this replaces
PAD = 1.0             # m of margin around the 40 x 30 floor


def _spans_lidar(cz, sz) -> bool:
    """True if a box centred at cz with height sz crosses the lidar plane."""
    return (cz - sz / 2) <= G.LIDAR_Z <= (cz + sz / 2)


def build(tier: str):
    tr = G.load_trained()
    w = int(round((G.L.MAP_W + 2 * PAD) / RES))
    h = int(round((G.L.MAP_H + 2 * PAD) / RES))
    ox, oy = -PAD, -PAD
    occ = np.zeros((h, w), np.uint8)          # 0 = free, 1 = occupied

    def fill_box(cx, cy, sx, sy):
        x0 = int(np.floor((cx - sx / 2 - ox) / RES))
        x1 = int(np.ceil((cx + sx / 2 - ox) / RES))
        y0 = int(np.floor((cy - sy / 2 - oy) / RES))
        y1 = int(np.ceil((cy + sy / 2 - oy) / RES))
        occ[max(0, y0):min(h, y1), max(0, x0):min(w, x1)] = 1

    def fill_circle(cx, cy, r):
        x0 = int(np.floor((cx - r - ox) / RES))
        x1 = int(np.ceil((cx + r - ox) / RES))
        y0 = int(np.floor((cy - r - oy) / RES))
        y1 = int(np.ceil((cy + r - oy) / RES))
        for j in range(max(0, y0), min(h, y1)):
            for i in range(max(0, x0), min(w, x1)):
                px, py = ox + (i + 0.5) * RES, oy + (j + 0.5) * RES
                if (px - cx) ** 2 + (py - cy) ** 2 <= r * r:
                    occ[j, i] = 1

    n_box = n_cyl = 0
    for kind, props in tr.items():
        for p in props:
            if kind == "wall":
                idx = int(p.name.rsplit("_", 1)[1])
                if tier == "open" and idx >= 4:
                    continue              # Tier-1 has no interior partitions
            if p.box is not None:
                cx, cy, cz = p.pose[:3]
                sx, sy, sz = p.box
                if not _spans_lidar(cz, sz):
                    continue              # floor tints, flags: invisible to the scan
                fill_box(cx, cy, sx, sy)
                n_box += 1
            elif p.cyl is not None:
                cx, cy, cz = p.pose[:3]
                r, ln = p.cyl
                if not _spans_lidar(cz, ln):
                    continue
                fill_circle(cx, cy, r)
                n_cyl += 1
    return occ, (ox, oy), n_box, n_cyl


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", default="walled", choices=["walled", "open"])
    a = ap.parse_args()

    occ, (ox, oy), n_box, n_cyl = build(a.tier)
    h, w = occ.shape
    # ROS map convention: 254 = free, 0 = occupied, row 0 of the PGM is the TOP
    img = np.where(occ == 1, 0, 254).astype(np.uint8)[::-1]
    stem = os.path.join(G.OUT, f"hospital_map_{a.tier}")
    with open(stem + ".pgm", "wb") as f:
        f.write(b"P5\n")
        f.write(f"# generated by sim/gen_map.py from worlds/hospital.world "
                f"({a.tier} tier)\n".encode())
        f.write(f"{w} {h}\n255\n".encode())
        f.write(img.tobytes())
    with open(stem + ".yaml", "w") as f:
        f.write(f"""image: hospital_map_{a.tier}.pgm
mode: trinary
resolution: {RES}
origin: [{ox}, {oy}, 0.0]
negate: 0
occupied_thresh: 0.65
free_thresh: 0.25
""")
    print(f"wrote {stem}.pgm / .yaml  ({w}x{h} @ {RES} m, origin ({ox}, {oy}))")
    print(f"  rasterised {n_box} boxes + {n_cyl} cylinders that cross z={G.LIDAR_Z} m")
    print(f"  occupied cells: {int(occ.sum())} ({100*occ.mean():.1f} % of the grid)")


if __name__ == "__main__":
    main()
