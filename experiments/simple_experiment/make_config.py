"""Build hospital_simple.yaml from the Tier-2 config by removing clutter.

Removed: every bed (ward rows, corridor overflow, V4 extra beds) and the static
people. Kept: all walls and doorways, the nurse desk, every room and cultural
zone (prayer room, gender wards), spawn points, tasks, prayer windows.

Line-based so the source YAML's comments and ordering survive.
"""
from __future__ import annotations
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
SRC = ROOT / "configs" / "hospital_v4.yaml"
DST = Path(__file__).resolve().parent / "hospital_simple.yaml"
DROP = re.compile(r'label:\s*"[^"]*(Bed|Static Person)[^"]*"')


def main():
    lines = SRC.read_text(encoding="utf-8").splitlines(keepends=True)
    out, i, dropped = [], 0, []
    in_obstacles = False
    while i < len(lines):
        ln = lines[i]
        if re.match(r"^static_obstacles:", ln):
            in_obstacles = True
        elif re.match(r"^\S", ln):
            in_obstacles = False
        # an obstacle entry = "  - polygon: ..." followed by its "    label:" line
        if in_obstacles and ln.lstrip().startswith("- polygon:") \
                and i + 1 < len(lines) and DROP.search(lines[i + 1]):
            dropped.append(DROP.search(lines[i + 1]).group(0))
            i += 2
            continue
        out.append(ln)
        i += 1
    header = ("# SIMPLIFIED TIER 2 (experiments/simple_experiment) — generated by\n"
              "# make_config.py from configs/hospital_v4.yaml; beds and static\n"
              f"# people removed ({len(dropped)} obstacles). Do not edit by hand.\n")
    DST.write_text(header + "".join(out), encoding="utf-8")
    print(f"wrote {DST.name}: removed {len(dropped)} obstacles")


if __name__ == "__main__":
    main()
