"""Generate configs/hospital_v4.yaml from deploy/ros2_stack/training/layout.py.

layout.py is the single source of truth for the NEW hospital floor plan (it
also generates the Gazebo world), so the benchmark's training config is
emitted from it rather than hand-written — the sim the 6 agents train in and
the Gazebo world the winner deploys to can never drift apart.

No main-code changes: the main pipeline (train_sac.py --config, evaluate.py
--config) already accepts any config path.

    .venv\\Scripts\\python.exe scripts\\gen_config_from_layout.py
"""
from __future__ import annotations

import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "deploy" / "ros2_stack" / "training"))
import layout  # noqa: E402

OUT = ROOT / "configs" / "hospital_v4.yaml"

# layout zone -> main-env room type (drives zone_onehot context + CVR zones)
TYPE_MAP = {
    "male_ward": "male_ward", "female_ward": "female_ward", "prayer": "prayer",
    "ward_icu_emerg": "emergency",
    "general_ward_1": "ward", "general_ward_2": "ward", "general_ward_3": "ward",
}
DENSITY = {
    "male_ward": 0.85, "female_ward": 0.85, "prayer": 0.4,
    "ward_icu_emerg": 0.95, "general_ward_1": 0.75, "general_ward_2": 0.75,
    "general_ward_3": 0.75,
}
URGENCY = {"ward_icu_emerg": 3, "prayer": 0}


def rect_yaml(x0, y0, x1, y1):
    def f(v):
        return f"{v:.2f}".rstrip("0").rstrip(".")
    return (f"[[{f(x0)}, {f(y0)}], [{f(x1)}, {f(y0)}], "
            f"[{f(x1)}, {f(y1)}], [{f(x0)}, {f(y1)}]]")


def room(rid, rtype, x0, y0, x1, y1, cultural, urgency, density, label):
    return (f"  - id: {rid}\n    type: {rtype}\n"
            f"    polygon: {rect_yaml(x0, y0, x1, y1)}\n"
            f"    cultural_zone: {'true' if cultural else 'false'}\n"
            f"    urgency_level: {urgency}\n"
            f"    default_pedestrian_density: {density}\n"
            f"    label: \"{label}\"\n")


def obstacle(x0, y0, x1, y1, label):
    return (f"  - polygon: {rect_yaml(x0, y0, x1, y1)}\n"
            f"    label: \"{label}\"\n")


def main() -> None:
    L = []
    L.append(f"""# LMIC-HospitalNav — V4 floor plan ("hardware layout, crowded")
# GENERATED by scripts/gen_config_from_layout.py on {time.strftime('%Y-%m-%d %H:%M')}
# from deploy/ros2_stack/training/layout.py — DO NOT EDIT BY HAND; edit
# layout.py and re-run the generator (the same layout.py also generates the
# Gazebo world, keeping sim and deployment geometry identical).
#
# Layout: three walled wards on the north strip (male/general-1/female), a
# 4 m full-width corridor at y=[13,17], and emergency/prayer/general-2/3
# south of it. One 1.0 m doorway per room. "Nurse station" is a desk in the
# corridor corner at ({layout.NURSE_DESK[0]}-{layout.NURSE_DESK[2]}, y~16) —
# a small nurse_station ZONE rectangle around it anchors the idle_return /
# task-start semantics (no walls). V4 crowding: {len(layout.EXTRA_BEDS)}
# extra beds in the corridor (both walls) and denser rows in every ward.

map:
  width_m: {layout.MAP_W}
  height_m: {layout.MAP_H}
  cell_size_m: 0.1

rooms:
  # open-floor fillers first (rasterization is in list order; later rooms
  # overwrite earlier ones where they overlap)""")
    L.append(room("open_south", "walkable", 0, 0, layout.MAP_W, 2.0,
                  False, 1, 0.3, "South Open Floor"))
    L.append(room("open_west", "walkable", 0, 2.0, 1.0, 13.0,
                  False, 1, 0.3, "West Open Floor"))
    L.append(room("open_east", "walkable", 35.0, 2.0, layout.MAP_W, 13.0,
                  False, 1, 0.4, "East Open Floor"))
    cx0, cy0, cx1, cy1 = layout.CORRIDOR
    L.append(room("main_corridor", "corridor", cx0, cy0, cx1, cy1,
                  False, 1, 0.9, "Main Corridor"))
    sx0, sy0, sx1, sy1 = layout.SOUTH_SIDE_CORRIDOR
    L.append(room("south_side_corridor", "corridor", sx0, sy0, sx1, sy1,
                  False, 1, 0.5, "South Side Corridor"))
    for (x0, y0, x1, y1, name, _doors) in layout.ROOMS:
        L.append(room(name, TYPE_MAP[name], x0, y0, x1, y1,
                      name in layout.CULTURAL, URGENCY.get(name, 1),
                      DENSITY[name], layout.ROOM_LABEL[name]))
    # nurse-desk zone LAST so it wins over main_corridor in its 2x2 m rect
    L.append(room("nurse_base", "nurse_station", 36.0, 14.0, 38.0, 16.0,
                  False, 3, 0.95, "Nurse Desk Area"))

    L.append("static_obstacles:")
    for i, w in enumerate(layout.WALLS):
        L.append(obstacle(*w, f"Wall {i}"))
    n_orig = len(layout.BEDS) - len(layout.EXTRA_BEDS)
    for i, b in enumerate(layout.BEDS):
        lbl = f"Bed {i}" if i < n_orig else f"V4 Extra Bed {i - n_orig}"
        L.append(obstacle(*b, lbl))
    L.append(obstacle(*layout.NURSE_DESK, "Nurse Desk"))
    for i, (px, py, pr) in enumerate(layout.PEOPLE):
        L.append(obstacle(px - pr, py - pr, px + pr, py + pr,
                          f"Static Person {i}"))

    sp = layout.START_POINT
    L.append(f"""robot_spawn_points:
  - [{sp[0]}, {sp[1]}]   # nurse desk (canonical start, matches Gazebo bringup)
  - [21.5, 15.0]   # corridor center (offset: a static person stands at (20,15))
  - [10.0, 15.0]   # corridor west
  - [18.5, 7.5]    # south side corridor

pedestrian_spawn_zones:
  medical_staff:
    - [[0.0, 13.0], [40.0, 17.0]]
    - [[1.0, 2.0], [9.0, 13.0]]
    - [[17.0, 2.0], [20.0, 13.0]]
  patient:
    - [[0.0, 17.0], [13.0, 30.0]]
    - [[13.0, 17.0], [27.0, 30.0]]
    - [[27.0, 17.0], [40.0, 30.0]]
    - [[20.0, 2.0], [35.0, 13.0]]
    - [[0.0, 13.0], [40.0, 17.0]]
  family_attendant:
    - [[0.0, 17.0], [13.0, 30.0]]
    - [[13.0, 17.0], [27.0, 30.0]]
    - [[27.0, 17.0], [40.0, 30.0]]
    - [[20.0, 2.0], [35.0, 13.0]]
    - [[0.0, 13.0], [40.0, 17.0]]
    - [[0.0, 0.0], [40.0, 2.0]]
  wheelchair:
    - [[0.0, 13.0], [40.0, 17.0]]
    - [[0.0, 0.0], [40.0, 2.0]]

tasks:
  STAT_medicine:
    start_room_id: nurse_base
    target_room_id: ward_icu_emerg
    urgency_level: 1.0
    deadline_s: 45
    label: "STAT Medicine Delivery"
  nurse_call:
    start_room_id: nurse_base
    target_room_id: female_ward
    urgency_level: 0.9
    deadline_s: 60
    label: "Nurse Call Response"
  specimen:
    start_room_id: general_ward_1
    target_room_id: general_ward_2
    urgency_level: 0.6
    deadline_s: 90
    label: "Specimen Transport"
  restock:
    start_room_id: nurse_base
    target_room_id: male_ward
    urgency_level: 0.3
    deadline_s: 180
    label: "Routine Restock"
  idle_return:
    start_room_id: male_ward
    target_room_id: nurse_base
    urgency_level: 0.1
    deadline_s: 300
    label: "Return to Base"

prayer_windows:
  - {{start_hour: 5.0,  end_hour: 6.5,  name: "Fajr"}}
  - {{start_hour: 12.0, end_hour: 13.0, name: "Dhuhr"}}
  - {{start_hour: 15.0, end_hour: 16.0, name: "Asr"}}
  - {{start_hour: 17.5, end_hour: 18.5, name: "Maghrib"}}
  - {{start_hour: 19.0, end_hour: 20.0, name: "Isha"}}

shift_change_windows:
  - {{start_hour: 7.5,  end_hour: 8.5}}
  - {{start_hour: 13.5, end_hour: 14.5}}
  - {{start_hour: 21.5, end_hour: 22.5}}""")

    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"[gen_config] wrote {OUT} "
          f"({len(layout.WALLS)} walls, {len(layout.BEDS)} beds "
          f"[{len(layout.EXTRA_BEDS)} V4 extras], desk, "
          f"{len(layout.PEOPLE)} static people)")


if __name__ == "__main__":
    main()
